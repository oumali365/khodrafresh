-- 🏗️ 01_schema_tables.sql – إنشاء وهيكلة جميع الجداول وحقول التزامن
-- متجر خُضرة - فاس (Khodra Store)
--
-- ينشئ / يحدّث الجداول الأساسية:
-- 1. products (المنتجات مع كافة التصنيفات والأسعار والمنشأ)
-- 2. orders (الطلبات مع حقول الحماية والمسارات الذكية بفاس والـ Soft Delete)
-- 3. reviews (تقييمات الزبائن مع الـ Soft Delete)
-- 4. store_settings (إعدادات المتجر مثل PIN المدير)
-- 5. order_security_logs (سجل محاولات السبام وتجاوز المعدل)
-- ==============================================================================

-- ─────────────────────────────────────────────────────────────────────────────
-- 1️⃣ جدول المنتجات (products)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('veg', 'fruit', 'dairy', 'grocery', 'drinks', 'cleaning')),
  type TEXT NOT NULL DEFAULT 'weight' CHECK (type IN ('weight', 'unit')),
  price NUMERIC(10,2) NOT NULL DEFAULT 0,
  unit_label TEXT,
  stock INTEGER NOT NULL DEFAULT 0,
  icon TEXT DEFAULT '🛒',
  image_url TEXT,
  active BOOLEAN DEFAULT TRUE,
  description TEXT,
  origin TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- في حال كان الجدول موجوداً مسبقاً، نضمن توفر جميع الأعمدة الجديدة
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS origin TEXT,
  ADD COLUMN IF NOT EXISTS description TEXT,
  ADD COLUMN IF NOT EXISTS image_url TEXT,
  ADD COLUMN IF NOT EXISTS unit_label TEXT,
  ADD COLUMN IF NOT EXISTS stock INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS active BOOLEAN DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_products_category_active ON public.products (category, active);
CREATE INDEX IF NOT EXISTS idx_products_id ON public.products (id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2️⃣ جدول الطلبات (orders) مع دعم الحماية والتوصيل الفوري والحذف الذكي
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  delivery_zone TEXT NOT NULL DEFAULT 'north' CHECK (delivery_zone IN ('north', 'central', 'south', 'east')),
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal NUMERIC(10,2) NOT NULL DEFAULT 0,
  delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0,
  total NUMERIC(10,2) NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'prepared', 'delivered', 'cancelled')),
  note TEXT,
  maps_link TEXT,
  -- حقول الحماية ومكافحة التكرار والسبام
  idempotency_key TEXT,
  client_id TEXT,
  device_fingerprint TEXT,
  ip_address TEXT,
  turnstile_token TEXT,
  security_flags JSONB DEFAULT '{}'::jsonb,
  -- حقول الحذف المرن والتزامن (لمنع اختفاء وظهور الطلبات مجدداً)
  is_deleted BOOLEAN DEFAULT FALSE,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ضمان توفر جميع الحقول حتى لو كان جدول orders قديماً في Supabase
ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS delivery_zone TEXT DEFAULT 'north',
  ADD COLUMN IF NOT EXISTS idempotency_key TEXT,
  ADD COLUMN IF NOT EXISTS client_id TEXT,
  ADD COLUMN IF NOT EXISTS device_fingerprint TEXT,
  ADD COLUMN IF NOT EXISTS ip_address TEXT,
  ADD COLUMN IF NOT EXISTS turnstile_token TEXT,
  ADD COLUMN IF NOT EXISTS security_flags JSONB DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- فهارس تسريع الأداء ومنع تكرار الطلبات وتسهيل تصفية الطلبات المحذوفة
CREATE INDEX IF NOT EXISTS idx_orders_created_at_desc ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders (status);
CREATE INDEX IF NOT EXISTS idx_orders_delivery_zone ON public.orders (delivery_zone);
CREATE INDEX IF NOT EXISTS idx_orders_is_deleted ON public.orders (is_deleted);
CREATE INDEX IF NOT EXISTS idx_orders_security_lookup ON public.orders (phone, client_id, ip_address, created_at DESC);

-- فهرس فريد لمنع تكرار الطلب بنفس مفتاح Idempotency
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_idempotency_key_unique
  ON public.orders (idempotency_key)
  WHERE idempotency_key IS NOT NULL;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3️⃣ جدول التقييمات (reviews)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author TEXT NOT NULL,
  neighborhood TEXT NOT NULL,
  rating SMALLINT NOT NULL DEFAULT 5 CHECK (rating >= 1 AND rating <= 5),
  comment TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'quality' CHECK (category IN ('all', 'quality', 'delivery', 'service')),
  verified BOOLEAN DEFAULT TRUE,
  is_deleted BOOLEAN DEFAULT FALSE,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.reviews
  ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_reviews_active ON public.reviews (is_deleted, created_at DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- 4️⃣ جدول إعدادات المتجر (store_settings)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.store_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  description TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 5️⃣ جدول سجلات الحماية (order_security_logs)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.order_security_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_type TEXT NOT NULL,
  phone TEXT,
  client_id TEXT,
  ip_address TEXT,
  reason TEXT,
  payload JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_security_logs_created_at ON public.order_security_logs (created_at DESC);
